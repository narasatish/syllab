/**
 * One-shot: convert the verified IG formula banks (scripts/instagram-bot/banks/*.json
 * with {chapter, subject, class, cover, slides:[{headline,sub}]}) into per-CHAPTER
 * FormulaSheet objects → src/data/formulaSheetsChapters.ts. This expands /formula-sheets
 * from 8 subject pages to ~100 chapter pages targeting "X formulas class Y" searches.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BANKS = path.join(__dirname, 'instagram-bot', 'banks');
const OUT = path.join(__dirname, '..', 'src', 'data', 'formulaSheetsChapters.ts');

const slugify = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
const subjEmoji = (s) => { const t = String(s || '').toLowerCase(); if (t.includes('math')) return '📐'; if (t.includes('phys')) return '⚛️'; if (t.includes('chem')) return '🧪'; if (t.includes('bio')) return '🧬'; return '📘'; };

const bySlug = new Map();
for (const f of readdirSync(BANKS)) {
  if (!f.endsWith('.json')) continue;
  let data; try { data = JSON.parse(readFileSync(path.join(BANKS, f), 'utf8')); } catch { continue; }
  if (!Array.isArray(data)) continue;
  for (const it of data) {
    if (!it.cover || !Array.isArray(it.slides) || !it.chapter || !it.class) continue;
    const cls = String(it.class);
    const subj = it.subject || 'Maths';
    const slug = `class-${cls}-${slugify(subj)}-${slugify(it.chapter)}`;
    if (bySlug.has(slug)) continue; // dedup across banks
    const formulas = it.slides
      .filter((s) => s && s.headline)
      .map((s) => ({ name: String(s.headline), formula: String(s.sub || '') }));
    if (formulas.length < 2) continue;
    const jeeNeet = Number(cls) >= 11 ? ', JEE & NEET' : '';
    bySlug.set(slug, {
      slug,
      title: `Class ${cls} ${subj}: ${it.chapter} Formulas`,
      classLevel: cls,
      subject: subj,
      emoji: subjEmoji(subj),
      intro: `All ${it.chapter} formulas for Class ${cls} ${subj} (CBSE / NCERT) on one page — fast revision for board exams${jeeNeet}. 100% free, no login, download as PDF.`,
      sections: [{ heading: `${it.chapter} — Key Formulas`, formulas }],
      faqs: [
        { q: `What are the most important ${it.chapter} formulas for Class ${cls}?`, a: `This sheet lists all ${formulas.length} key ${it.chapter} formulas from the Class ${cls} ${subj} CBSE/NCERT syllabus, ready for quick revision.` },
        { q: `Is this ${it.chapter} formula sheet free to download?`, a: `Yes — every Syllab.in formula sheet is 100% free, needs no login, and can be saved as a PDF.` },
      ],
    });
  }
}

const sheets = [...bySlug.values()].sort((a, b) => a.slug.localeCompare(b.slug));
const banner = `// AUTO-GENERATED by scripts/gen-formula-chapters.mjs from the verified formula banks.\n// Per-chapter formula sheets — do not hand-edit; re-run the script to regenerate.\nimport type { FormulaSheet } from './formulaSheets';\n\nexport const FORMULA_SHEETS_CHAPTERS: FormulaSheet[] = `;
writeFileSync(OUT, banner + JSON.stringify(sheets, null, 2) + ';\n', 'utf8');
console.log(`Wrote ${sheets.length} chapter formula sheets → ${OUT}`);
console.log('by class:', JSON.stringify(sheets.reduce((m, s) => { m[s.classLevel] = (m[s.classLevel] || 0) + 1; return m; }, {})));
