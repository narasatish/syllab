/**
 * Integrate subagent-authored story lessons into one typed data file.
 * Reads the raw agent outputs (a direct JSON file + persisted tool-results),
 * strips markdown fences / the [{type:text,text}] wrapper, validates each lesson
 * against the StoryLesson shape, dedupes by slug, and writes
 * src/data/storyLessonsGenerated.ts. Re-runnable.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GEN_DIR = path.join(ROOT, 'src', 'data', 'story-gen');

// All subagent-authored class files live in src/data/story-gen/class-*.json.
const SOURCES = (existsSync(GEN_DIR) ? readdirSync(GEN_DIR) : [])
  .filter((f) => /^class-[\w-]+\.json$/.test(f))
  .sort()
  .map((f) => [f.replace('.json', ''), path.join(GEN_DIR, f)]);

/** Pull the JSON-array text out of whatever wrapper/fences the agent used. */
function extractArrayText(raw) {
  let s = raw.trim();
  // Unwrap [{ "type":"text", "text": "..." }]
  try {
    const w = JSON.parse(s);
    if (Array.isArray(w) && w[0] && typeof w[0].text === 'string') s = w[0].text;
  } catch { /* not wrapped */ }
  // Strip ```json … ``` fences
  s = s.replace(/```json/gi, '').replace(/```/g, '').trim();
  // Slice from first [ to last ]
  const a = s.indexOf('[');
  const b = s.lastIndexOf(']');
  if (a >= 0 && b > a) s = s.slice(a, b + 1);
  return s;
}

const valid = [];
const report = [];
for (const [name, fp] of SOURCES) {
  if (!existsSync(fp)) { report.push(`${name}: MISSING (${path.basename(fp)})`); continue; }
  let arr;
  try {
    arr = JSON.parse(extractArrayText(readFileSync(fp, 'utf8')));
  } catch (e) {
    report.push(`${name}: ❌ PARSE FAIL — ${e.message.slice(0, 90)}`);
    continue;
  }
  let ok = 0;
  for (const l of Array.isArray(arr) ? arr : []) {
    if (l && typeof l.slug === 'string' && l.classLevel && l.chapter && l.title && Array.isArray(l.slides) && l.slides.length) {
      // Minimal normalisation
      l.subject = l.subject || 'Mathematics';
      l.characters = Array.isArray(l.characters) ? l.characters : [];
      valid.push(l);
      ok++;
    }
  }
  report.push(`${name}: ✓ ${ok} lessons`);
}

// Dedupe by slug
const seen = new Set();
const lessons = valid.filter((l) => (seen.has(l.slug) ? false : (seen.add(l.slug), true)));

console.log(report.join('\n'));
console.log(`\nTOTAL valid lessons: ${lessons.length}`);
console.log('by class:', JSON.stringify(lessons.reduce((m, l) => ((m[l.classLevel] = (m[l.classLevel] || 0) + 1), m), {})));

// PERF: the full lessons (~14MB as TS) must never live in the JS bundle. We emit:
//   1. public/story-lessons/class-{n}.json  — full lessons, fetched on demand
//   2. src/data/storyLessonsIndex.ts        — tiny metadata index (bundled) so the
//      UI can synchronously know which chapters have a story and where to fetch it.
import { mkdirSync } from 'node:fs';
const PUB_DIR = path.join(ROOT, 'public', 'story-lessons');
mkdirSync(PUB_DIR, { recursive: true });
const byClass = {};
for (const l of lessons) (byClass[l.classLevel] ??= []).push(l);
for (const [cls, arr] of Object.entries(byClass)) {
  writeFileSync(path.join(PUB_DIR, `class-${cls}.json`), JSON.stringify(arr));
}
console.log(`→ wrote ${Object.keys(byClass).length} files to public/story-lessons/`);

const index = lessons.map((l) => ({
  slug: l.slug,
  classLevel: l.classLevel,
  subject: l.subject,
  chapter: l.chapter,
  ...(l.chapterAliases && l.chapterAliases.length ? { chapterAliases: l.chapterAliases } : {}),
}));
const idxOut =
  `// AUTO-GENERATED by scripts/integrate-story-lessons.mjs — lightweight lesson index.\n` +
  `// Full lessons live in public/story-lessons/class-{n}.json (fetched on demand).\n` +
  `export interface StoryLessonIndexEntry { slug: string; classLevel: string; subject: string; chapter: string; chapterAliases?: string[] }\n\n` +
  `export const STORY_LESSONS_INDEX: StoryLessonIndexEntry[] = ${JSON.stringify(index)};\n`;
writeFileSync(path.join(ROOT, 'src', 'data', 'storyLessonsIndex.ts'), idxOut, 'utf8');
console.log('→ wrote src/data/storyLessonsIndex.ts (' + index.length + ' entries)');
