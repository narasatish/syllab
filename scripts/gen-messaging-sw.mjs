/**
 * gen-messaging-sw.mjs — writes public/firebase-messaging-sw.js from your env.
 *
 * The FCM background service worker can't read import.meta.env, so it needs the
 * (public) Firebase web config baked in. This reads the same VITE_FIREBASE_* vars
 * the app uses and stamps them into the SW. Run it before `vite build`, or once
 * after you add the keys. If config is missing it writes a harmless no-op SW.
 *
 * Usage:  node scripts/gen-messaging-sw.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'public', 'firebase-messaging-sw.js');

// Merge .env files (later wins) + process.env so CI secrets take precedence.
const env = {};
for (const f of ['.env', '.env.local', '.env.production', '.env.production.local']) {
  const p = path.join(ROOT, f);
  if (!existsSync(p)) continue;
  for (const line of readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (!m) continue;
    let v = m[2].trim().replace(/^["']|["']$/g, '');
    env[m[1]] = v;
  }
}
Object.assign(env, Object.fromEntries(Object.entries(process.env).filter(([k]) => k.startsWith('VITE_FIREBASE_'))));

const cfg = {
  apiKey: env.VITE_FIREBASE_API_KEY,
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN,
  projectId: env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: env.VITE_FIREBASE_APP_ID,
};

const configured = cfg.projectId && cfg.messagingSenderId && cfg.apiKey;
const body = configured
  ? `// AUTO-GENERATED by scripts/gen-messaging-sw.mjs — do not edit by hand.
importScripts('https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js');
firebase.initializeApp(${JSON.stringify(cfg)});
const messaging = firebase.messaging();
messaging.onBackgroundMessage((payload) => {
  const n = payload.notification || {};
  self.registration.showNotification(n.title || 'Syllab', {
    body: n.body || '', icon: '/icon.svg', badge: '/icon.svg',
    data: { url: (payload.fcmOptions && payload.fcmOptions.link) || '/' },
  });
});
self.addEventListener('notificationclick', (e) => {
  e.notification.close();
  e.waitUntil(clients.openWindow((e.notification.data && e.notification.data.url) || '/'));
});
`
  : `// No Firebase Cloud Messaging config found at build time — inert placeholder.
// Add VITE_FIREBASE_* env vars and re-run scripts/gen-messaging-sw.mjs to enable push.
self.addEventListener('install', () => self.skipWaiting());
`;

writeFileSync(OUT, body, 'utf8');
console.log(`${configured ? '✓ wrote FCM' : '· wrote inert'} messaging SW → ${path.relative(ROOT, OUT)}`);
