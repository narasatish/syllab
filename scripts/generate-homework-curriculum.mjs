/**
 * generate-homework-curriculum.mjs
 *
 * Builds src/data/homeworkCurriculum.ts — a compact, class-appropriate
 * class → subject → chapter[] map for the AI Tuition Teacher's dependent
 * dropdowns (so Class 1 never shows "Algebra").
 *
 * Source of truth:
 *   • Classes 6–12: derived from public/data/ncert-solutions.json keys
 *     ("<class>::<Subject>::<chapter-slug>") — the same chapters the rest of
 *     the app already serves.
 *   • Classes 1–5: hand-authored CBSE foundational chapters (below).
 *
 * Run: node scripts/generate-homework-curriculum.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

const SMALL = new Set(['and', 'of', 'the', 'a', 'an', 'to', 'in', 'on', 'for', 'with', 'its']);
const titleCase = (slug) =>
  slug
    .split('-')
    .filter(Boolean)
    .map((w, i) => (i > 0 && SMALL.has(w) ? w : w.charAt(0).toUpperCase() + w.slice(1)))
    .join(' ');

// ── Classes 6–12 from NCERT solutions keys ──
const ncert = JSON.parse(readFileSync(join(ROOT, 'public/data/ncert-solutions.json'), 'utf8').replace(/^﻿/, ''));
const map = {}; // { "6": { "Mathematics": Set, ... }, ... }
for (const key of Object.keys(ncert)) {
  const [cls, subject, slug] = key.split('::');
  if (!cls || !subject || !slug) continue;
  (map[cls] ||= {});
  (map[cls][subject] ||= new Set());
  map[cls][subject].add(titleCase(slug));
}

// ── Classes 1–5 (hand-authored, CBSE foundational) ──
const JUNIOR = {
  '1': {
    Mathematics: ['Numbers 1 to 9', 'Numbers up to 20', 'Addition', 'Subtraction', 'Shapes and Space', 'Measurement', 'Time', 'Money', 'Patterns'],
    English: ['The Alphabet', 'Three Letter Words', 'Naming Words (Nouns)', 'Action Words (Verbs)', 'Rhyming Words', 'Reading Simple Sentences'],
    EVS: ['My Family', 'My Body', 'Plants Around Us', 'Animals Around Us', 'Good Habits', 'Food We Eat'],
  },
  '2': {
    Mathematics: ['Numbers up to 100', 'Addition with Carrying', 'Subtraction with Borrowing', 'Shapes', 'Measurement of Length', 'Time and Calendar', 'Money', 'Multiplication Tables', 'Patterns'],
    English: ['Nouns', 'Pronouns', 'Verbs', 'Adjectives', 'Articles (a, an, the)', 'Reading Comprehension', 'Picture Composition'],
    EVS: ['Living and Non-living', 'Plants', 'Animals and Their Homes', 'Our Family and Festivals', 'Water', 'Means of Transport'],
  },
  '3': {
    Mathematics: ['Numbers up to 1000', 'Addition and Subtraction', 'Multiplication', 'Division', 'Fractions', 'Geometry - Shapes', 'Measurement', 'Time', 'Money', 'Data Handling'],
    English: ['Nouns and Genders', 'Tenses', 'Adjectives', 'Prepositions', 'Conjunctions', 'Comprehension', 'Paragraph Writing'],
    EVS: ['Plants and Their Parts', 'Animals', 'The Human Body', 'Our Food', 'Houses Around Us', 'Travel and Transport', 'Water and Air'],
  },
  '4': {
    Mathematics: ['Large Numbers', 'Addition and Subtraction', 'Multiplication', 'Division', 'Factors and Multiples', 'Fractions', 'Geometry', 'Perimeter and Area', 'Measurement', 'Time', 'Money', 'Data Handling'],
    English: ['Parts of Speech', 'Tenses', 'Active and Passive Voice', 'Punctuation', 'Comprehension', 'Letter Writing', 'Essay Writing'],
    EVS: ['Plants - Adaptations', 'Animals - Adaptations', 'The Human Body and Senses', 'Food and Digestion', 'Our Environment', 'Natural Resources', 'Safety and First Aid'],
  },
  '5': {
    Mathematics: ['Large Numbers and Operations', 'Factors and Multiples', 'Fractions', 'Decimals', 'Percentage', 'Geometry', 'Perimeter, Area and Volume', 'Measurement', 'Time and Temperature', 'Data Handling', 'Patterns'],
    English: ['Parts of Speech', 'Tenses', 'Voice', 'Direct and Indirect Speech', 'Comprehension', 'Letter and Notice Writing', 'Story and Essay Writing'],
    EVS: ['Super Senses', 'Plants and Animals', 'The Human Body', 'Food and Health', 'Water and Its Uses', 'Natural Disasters', 'Our Environment', 'Travel and Communication'],
  },
};

// Merge: build final object with sorted chapter arrays.
const out = {};
for (const cls of ['1', '2', '3', '4', '5']) out[cls] = JUNIOR[cls];
for (const cls of Object.keys(map).sort((a, b) => Number(a) - Number(b))) {
  out[cls] = {};
  for (const subject of Object.keys(map[cls]).sort()) {
    out[cls][subject] = [...map[cls][subject]].sort();
  }
}

const header = `// AUTO-GENERATED by scripts/generate-homework-curriculum.mjs — do not edit by hand.
// Class → Subject → Chapter[] for the AI Tuition Teacher dependent dropdowns.
// Classes 1–5 are hand-authored CBSE foundational chapters; 6–12 come from
// the app's NCERT solutions dataset.

export type CurriculumMap = Record<string, Record<string, string[]>>;

export const HOMEWORK_CURRICULUM: CurriculumMap = ${JSON.stringify(out, null, 2)};

/** Subjects available for a class label like "Class 6" or "6". */
export function subjectsForClass(classLabel: string): string[] {
  const cls = String(classLabel).replace(/[^0-9]/g, '');
  return Object.keys(HOMEWORK_CURRICULUM[cls] || {});
}

/** Chapters for a class + subject. Empty array if none (caller offers free text). */
export function chaptersFor(classLabel: string, subject: string): string[] {
  const cls = String(classLabel).replace(/[^0-9]/g, '');
  return (HOMEWORK_CURRICULUM[cls] && HOMEWORK_CURRICULUM[cls][subject]) || [];
}
`;

writeFileSync(join(ROOT, 'src/data/homeworkCurriculum.ts'), header, 'utf8');

const classes = Object.keys(out).length;
const chapters = Object.values(out).reduce((n, subs) => n + Object.values(subs).reduce((m, arr) => m + arr.length, 0), 0);
console.log(`✅ homeworkCurriculum.ts written: ${classes} classes, ${chapters} chapters.`);
