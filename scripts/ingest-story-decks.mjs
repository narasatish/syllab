/**
 * ingest-story-decks.mjs — scan public/story-decks/ for uploaded chapter slide
 * decks and (re)write src/data/uploadedDecksData.ts.
 *
 * Drop a folder per chapter, named  class-{n}-{chapter-slug}, containing the PPT
 * exported as images (Slide1.png, Slide2.png …). Run this script (runs automatically
 * in `npm run build`) and the chapter's "Lesson" button opens your slides.
 *
 * Matches each folder to the real chapter title/subject via docs/syllabus-chapters.csv
 * when possible; otherwise derives a title from the slug.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DECKS_DIR = path.join(ROOT, 'public', 'story-decks');
const OUT = path.join(ROOT, 'src', 'data', 'uploadedDecksData.ts');
const IMG = /\.(png|jpe?g|webp)$/i;
const slugify = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Build slug -> {chapter, subject} per class from the CSV (best-effort nice titles).
const csvMap = {};
const csvPath = path.join(ROOT, 'docs', 'syllabus-chapters.csv');
if (existsSync(csvPath)) {
  const lines = readFileSync(csvPath, 'utf8').split(/\r?\n/).slice(1);
  for (const line of lines) {
    const m = line.match(/^([^,]*),(\d+),("(?:[^"]|"")*"|[^,]*),("(?:[^"]|"")*"|[^,]*)$/);
    if (!m) continue;
    const cls = m[2];
    const subject = m[3].replace(/^"|"$/g, '').replace(/""/g, '"');
    const chapter = m[4].replace(/^"|"$/g, '').replace(/""/g, '"');
    csvMap[`${cls}|${slugify(chapter)}`] = { chapter, subject };
  }
}

const titleFromSlug = (slug) => slug.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
const slideNo = (f) => { const m = f.match(/(\d+)/); return m ? parseInt(m[1], 10) : 9999; };

const decks = [];
if (existsSync(DECKS_DIR)) {
  for (const folder of readdirSync(DECKS_DIR)) {
    const dir = path.join(DECKS_DIR, folder);
    if (!statSync(dir).isDirectory()) continue;
    const cm = folder.match(/^class-(\d+)-(.+)$/i);
    if (!cm) { console.warn(`  ⚠ skipping "${folder}" — name must be class-{n}-{chapter-slug}`); continue; }
    const classLevel = cm[1];
    const chapterSlug = slugify(cm[2]);
    const files = readdirSync(dir).filter((f) => IMG.test(f)).sort((a, b) => slideNo(a) - slideNo(b) || a.localeCompare(b));
    if (!files.length) { console.warn(`  ⚠ "${folder}" has no images`); continue; }
    const meta = csvMap[`${classLevel}|${chapterSlug}`];
    decks.push({
      key: `class-${classLevel}-${chapterSlug}`,
      classLevel,
      chapterSlug,
      chapter: meta ? meta.chapter : titleFromSlug(chapterSlug),
      subject: meta ? meta.subject : undefined,
      slides: files.map((f) => `/story-decks/${folder}/${f}`),
    });
  }
}

decks.sort((a, b) => Number(a.classLevel) - Number(b.classLevel) || a.chapterSlug.localeCompare(b.chapterSlug));
const banner = `// AUTO-GENERATED by scripts/ingest-story-decks.mjs — do not edit by hand.\n// One entry per uploaded slide deck found in public/story-decks/<class-n-slug>/.\nimport type { UploadedDeck } from './uploadedDecks';\n\n`;
writeFileSync(OUT, `${banner}export const UPLOADED_DECKS: UploadedDeck[] = ${JSON.stringify(decks, null, 2)};\n`, 'utf8');
console.log(`✓ ingested ${decks.length} uploaded deck(s), ${decks.reduce((n, d) => n + d.slides.length, 0)} slides`);
for (const d of decks) console.log(`   ${d.key} — ${d.slides.length} slides${d.subject ? ` (${d.subject})` : ''}`);
