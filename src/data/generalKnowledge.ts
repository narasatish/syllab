// Helper function to get daily GK quiz
export function getDailyGKQuiz(date?: Date): GKItem[] {
  const d = date || new Date();
  const dayOfYear = Math.floor((d.getTime() - new Date(d.getFullYear(), 0, 0).getTime()) / 86400000);
  const seed = dayOfYear;

  // Shuffle array with seeded random for consistent daily questions
  const shuffled = [...GK_QUESTIONS].sort((a, b) => {
    const hashA = a.id.split('').reduce((h, c) => ((h << 5) - h) + c.charCodeAt(0), 0);
    const hashB = b.id.split('').reduce((h, c) => ((h << 5) - h) + c.charCodeAt(0), 0);
    return (hashA + seed) % 1000 - (hashB + seed) % 1000;
  });

  return shuffled.slice(0, 10);
}

// Helper function to get questions by category
export function getQuestionsByCategory(category: GKItem['category']): GKItem[] {
  return GK_QUESTIONS.filter((q) => q.category === category);
}

// Helper function to get questions by class level
export function getQuestionsByClass(classLevel: number): GKItem[] {
  return GK_QUESTIONS.filter((q) => q.classLevels.includes(classLevel));
}
