/** Pick today's "word of the day" deterministically. */
export function getWordOfDay(level: Level): VocabWord {
  const pool = getVocabByLevel(level);
  const today = new Date();
  const seed = today.getFullYear() * 1000 + today.getMonth() * 32 + today.getDate();
  return pool[seed % pool.length];
}
